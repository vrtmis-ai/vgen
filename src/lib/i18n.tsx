export type TKey = keyof typeof dict.fa;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  /** locale-aware integer formatting (fa digits in Persian) */
  n: (v: number) => string;
  /** a coin amount — like `n`, but keeps up to two decimals. See coinDigits. */
  c: (v: number) => string;
}

const Ctx = createContext<I18n>({
  lang: "fa",
  setLang: () => undefined,
  t: (k) => dict.fa[k],
  n: (v) => v.toLocaleString(FA),
  c: (v) => coinDigits(v, FA),
});

export function LanguageProvider({ initialLang = "fa", children }: { initialLang?: Lang; children: React.ReactNode }) {
  // Seeded from the cookie the server already read, so the first client render
  // agrees with the server's markup. Never re-read here.
  const [lang, setLang] = useState<Lang>(initialLang);

  useEffect(() => {
    try {
      document.cookie = `${LANG_COOKIE}=${lang};path=/;max-age=${LANG_COOKIE_MAX_AGE_SECONDS};samesite=lax`;
    } catch {
      // cookies blocked — language just won't persist
    }
    // The server already set both for the initial language. Keeping this write
    // is what makes a mid-session switch flip direction without a reload.
    document.documentElement.lang = lang;
    document.documentElement.dir = dirFor(lang);
  }, [lang]);

  const t = (k: TKey) => dict[lang][k] ?? dict.fa[k];
  // One locale decides digits, grouping and decimal together. Splitting them —
  // English grouping, Persian digits — is what put an ASCII comma inside a
  // Persian figure everywhere a number is printed.
  const locale: NumberLocale = lang === "fa" ? FA : EN;
  const n = (v: number) => v.toLocaleString(locale);
  const c = (v: number) => coinDigits(v, locale);

  return <Ctx.Provider value={{ lang, setLang, t, n, c }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  return useContext(Ctx);
}
